// Suppression patterns are built by concatenation so this file does not trip
// Verify's own suppressions guard.
var (
	nolint = "//" + "nolint"
	skip   = "t.Sk" + "ip(\"x\")"
	tsIgn  = "// @ts" + "-ignore"
)

func git(t *testing.T, dir string, args ...string) {
	t.Helper()
	c := exec.CommandContext(t.Context(), "git", args...) // #nosec G204 -- test helper
	c.Dir = dir
	c.Env = append(os.Environ(), "GIT_AUTHOR_NAME=t", "GIT_AUTHOR_EMAIL=t@e", "GIT_COMMITTER_NAME=t", "GIT_COMMITTER_EMAIL=t@e")
	if out, err := c.CombinedOutput(); err != nil {
		t.Fatalf("git %v: %v %s", args, err, out)
	}
}

func put(t *testing.T, dir, name, body string) {
	t.Helper()
	p := filepath.Join(dir, name)
	if err := os.MkdirAll(filepath.Dir(p), 0o750); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(body), 0o600); err != nil {
		t.Fatal(err)
	}
}

func rev(t *testing.T, repo *gitx.Repo, r string) string {
	t.Helper()
	s, err := repo.Resolve(t.Context(), r)
	if err != nil {
		t.Fatal(err)
	}
	return s
}

func ids(fs []state.Finding) string {
	var s []string
	for _, f := range fs {
		s = append(s, f.ID)
	}
	return strings.Join(s, " ")
}

func run(t *testing.T) (string, []state.Finding) {
	t.Helper()
	bin := t.TempDir()
	gp, err := exec.LookPath("git")
	if err != nil {
		t.Skip("git missing")
	}
	if err := os.Symlink(gp, filepath.Join(bin, "git")); err != nil {
		t.Fatal(err)
	}
	t.Setenv("PATH", bin)
	dir, _ := filepath.EvalSymlinks(t.TempDir())
	git(t, dir, "init", "-q", "-b", "main")
	put(t, dir, "gen.go", "// Code generated by x. DO NOT EDIT.\npackage a\n")
	put(t, dir, "a_test.go", "package a\n\nfunc TestA(t *testing.T) {}\n\nfunc TestB(t *testing.T) {}\n")
	put(t, dir, "b_test.go", "package a\n")
	put(t, dir, "x.go", "package a\n")
	git(t, dir, "add", ".")
	git(t, dir, "commit", "-q", "-m", "base")
	put(t, dir, "gen.go", "// Code generated by x. DO NOT EDIT.\npackage a\n\nvar X = 1\n")
	put(t, dir, "a_test.go", "package a\n\nfunc TestA(t *testing.T) {\n\t"+skip+"\n}\n")
	put(t, dir, "x.go", "package a\n\nvar Y = 1 "+nolint+"\n")
	put(t, dir, "y.ts", tsIgn+"\n")
	put(t, dir, ".golangci.yml", "version: \"2\"\n")
	if err := os.Remove(filepath.Join(dir, "b_test.go")); err != nil {
		t.Fatal(err)
	}
	git(t, dir, "add", "-A")
	git(t, dir, "commit", "-q", "-m", "change")
	repo, err := gitx.Open(t.Context(), dir)
	if err != nil {
		t.Fatal(err)
	}
	fs, err := Run(t.Context(), Input{Repo: repo, Base: rev(t, repo, "HEAD~1"), SHA: rev(t, repo, "HEAD"), Config: config.Default()})
	if err != nil {
		t.Fatal(err)
	}
	return dir, fs
}

func TestGuardsFire(t *testing.T) {
	_, fs := run(t)
	got := ids(fs)
	for _, want := range []string{
		"guard:suppressions:x.go:3", "guard:suppressions:a_test.go:4",
		"guard:suppressions:y.ts:1", "guard:tests-removed:b_test.go", "guard:tests-removed:a_test.go",
		"guard:generated:gen.go", "guard:config:.golangci.yml",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("missing %s in %s", want, got)
		}
	}
	for _, f := range fs {
		if f.Source != state.SourceGuard || f.State != state.StateOpen || f.Rule != strings.Join(strings.SplitN(f.ID, ":", 3)[:2], ":") {
			t.Errorf("%+v", f)
		}
		if f.Rule == "guard:config" && f.Severity != state.SeverityNote {
			t.Errorf("config must be a note: %+v", f)
		}
	}
}

func TestParseLineDiff(t *testing.T) {
	d, err := gitx.ParseLineDiff("diff --git a/f b/f\n--- a/f\n+++ b/f\n@@ -2 +2,2 @@\n-old\n+n1\n+n2\n")
	if err != nil || len(d.Added) != 2 || d.Added[1].Number != 3 || d.Removed[0].Number != 2 {
		t.Fatalf("%+v %v", d, err)
	}
}

func TestGoSubtestRemovalConservative(t *testing.T) {
	d := &gitx.LineDiff{Removed: []gitx.Line{{Path: "example_test.go", Text: `t.Run("edge", func(t *testing.T) {})`}}, Added: []gitx.Line{{Path: "example_test.go", Text: `// an unrelated comment`}}}
	if got := testsRemoved(d); len(got) != 1 || got[0].Rule != "guard:tests-removed" {
		t.Fatalf("subtest removal bypass: %+v", got)
	}
	d.Added = []gitx.Line{{Path: "example_test.go", Text: `t.Run("replacement", func(t *testing.T) {})`}}
	if got := testsRemoved(d); len(got) != 0 {
		t.Fatalf("replacement wrongly blocked: %+v", got)
	}
}
