func TestBattleDeletedTestHasUniqueFinding(t *testing.T) {
	const p = "example_test.go"
	got := testsRemoved(&gitx.LineDiff{DeletedFiles: []string{p}, Removed: []gitx.Line{{Path: p, Number: 1, Text: "func TestExample(t *testing.T) {"}}})
	seen := map[string]bool{}
	for _, f := range got {
		if seen[f.ID] {
			t.Errorf("duplicate finding ID %q: %+v", f.ID, got)
		}
		seen[f.ID] = true
	}
	if len(got) != 1 {
		t.Errorf("deleted test should have one file-level finding, got %d", len(got))
	}
}

func TestBattleModifiedSymlinkIsNotGenerated(t *testing.T) {
	dir := t.TempDir()
	git(t, dir, "init", "-q", "-b", "main")
	p := filepath.Join(dir, "link")
	if err := os.Symlink("first", p); err != nil {
		t.Fatal(err)
	}
	git(t, dir, "add", ".")
	git(t, dir, "commit", "-qm", "base")
	r, err := gitx.Open(t.Context(), dir)
	if err != nil {
		t.Fatal(err)
	}
	base := rev(t, r, "HEAD")
	if err := os.Remove(p); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink("second", p); err != nil {
		t.Fatal(err)
	}
	git(t, dir, "commit", "-qam", "retarget symlink")
	fs, err := Run(t.Context(), Input{Repo: r, Base: base, SHA: rev(t, r, "HEAD")})
	if err != nil {
		t.Fatal(err)
	}
	if len(fs) != 0 {
		t.Fatalf("symlink retarget produces unexpected findings: %+v", fs)
	}
}

func BenchmarkBattleGuardsLargeDiff(b *testing.B) {
	for _, size := range []struct {
		name  string
		files int
	}{{"100", 100}, {"10000", 10000}} {
		b.Run(size.name, func(b *testing.B) {
			d := &gitx.LineDiff{}
			for i := 0; i < size.files; i++ {
				p := fmt.Sprintf("src/component%d.test.ts", i)
				d.Added = append(d.Added, gitx.Line{Path: p, Number: 1, Text: "test('replacement', () => {});"})
				d.Removed = append(d.Removed, gitx.Line{Path: p, Number: 1, Text: "test('before', () => {});"})
				d.Modified = append(d.Modified, p)
			}
			b.ReportAllocs()
			b.ResetTimer()
			for b.Loop() {
				_ = suppressions(d)
				_ = testsRemoved(d)
				_ = configNotes(d)
			}
		})
	}
}

func TestBattleGeneratedRegularReplacedBySymlinkStillBlocked(t *testing.T) {
	dir := t.TempDir()
	git(t, dir, "init", "-q", "-b", "main")
	put(t, dir, "generated.go", "// Code generated by fixture. DO NOT EDIT.\npackage fixture\n")
	git(t, dir, "add", ".")
	git(t, dir, "commit", "-qm", "base")
	r, err := gitx.Open(t.Context(), dir)
	if err != nil {
		t.Fatal(err)
	}
	base := rev(t, r, "HEAD")
	p := filepath.Join(dir, "generated.go")
	if err := os.Remove(p); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink("target", p); err != nil {
		t.Fatal(err)
	}
	git(t, dir, "add", ".")
	git(t, dir, "commit", "-qm", "replace generated content")
	fs, err := Run(t.Context(), Input{Repo: r, Base: base, SHA: rev(t, r, "HEAD")})
	if err != nil {
		t.Fatal(err)
	}
	for _, f := range fs {
		if f.Rule == "guard:generated" && f.Path == "generated.go" {
			return
		}
	}
	t.Fatalf("generated regular-file replacement escaped protection: %+v", fs)
}
